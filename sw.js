/* =========================================================
   SERVICE WORKER — installable, offline-first app shell

   Three caches, each with its own rule:

   - shell-<VERSION>: every file the planner needs to boot
     (HTML, CSS, JS modules, Leaflet, icons). Precached on
     install, served cache-first, and swapped wholesale when a
     new VERSION ships — activate deletes every other shell-*.
     VERSION and SHELL are written by scripts/build-sw.mjs from
     a hash of those files, so any change to any of them
     changes this file, which is what makes the browser see an
     update at all. Run it before committing shell changes.
   - fonts: Google Fonts CSS + font files, cached as they're
     used (stale-while-revalidate), so text keeps its faces
     offline.
   - photos-<room>: stop photos for the last few trips opened,
     filled on the page's request (js/pwa.js) rather than as a
     side effect of browsing, so what's kept is exactly "this
     trip's photos" and old trips can be dropped as a unit.

   Deliberately NOT handled — they go straight to the network:
   map tiles and routing (known v1 limitation), Firebase,
   geocoding, and any CORS-mode fetch. That last one matters:
   the "Take this trip offline" export fetches photos in CORS
   mode to re-encode them, and must never be handed an opaque
   cached copy it can't read.
   ========================================================= */

